/**
 * Tab displaying the exact layout aesthetic generated by the Python script:
 * 1. Navy Banner with title/subject/topic/exam/set number + edit details action
 * 2. Section I: Question Set (cards or borderless exam layout)
 * 3. Section II: Answer Key Grid (compact matrix)
 * 4. Section III: Detailed Explanations with option text included.
 */
@Composable
fun PaperViewTab(
    paper: QuestionPaper,
    isCardBoxed: Boolean = true,
    onToggleCardBoxed: () -> Unit = {},
    onEditMetadata: () -> Unit = {},
    modifier: Modifier = Modifier
) {
    val colors = ExamTheme.colors

    LazyColumn(
        modifier = modifier
            .fillMaxSize()
            .padding(horizontal = 16.dp),
        verticalArrangement = Arrangement.spacedBy(10.dp)
    ) {
        // Top Space
        item { Spacer(modifier = Modifier.height(6.dp)) }

        // 1. Signature Navy Banner (from draw_first_page)
        item {
            HeaderBanner(
                metadata = paper.metadata,
                totalQuestions = paper.questions.size,
                onEditClick = onEditMetadata
            )
        }

        // Section I Title: Questions + Layout Style Switcher
        item {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(top = 8.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                PartHeader(
                    partNumber = "SECTION I",
                    title = "Question Paper",
                    countText = "${paper.questions.size} Questions",
                    icon = Icons.AutoMirrored.Filled.Assignment,
                    modifier = Modifier.weight(1f)
                )

                // Layout pill toggle: Card Boxed vs Clean Borderless
                Surface(
                    modifier = Modifier.clickable { onToggleCardBoxed() },
                    shape = RoundedCornerShape(16.dp),
                    color = colors.tealLight,
                    border = BorderStroke(0.6.dp, colors.border)
                ) {
                    Row(
                        modifier = Modifier.padding(horizontal = 9.dp, vertical = 5.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Icon(
                            imageVector = if (isCardBoxed) Icons.Default.Dashboard else Icons.Default.ListAlt,
                            contentDescription = "Toggle layout style",
                            tint = colors.tealDark,
                            modifier = Modifier.size(14.dp)
                        )
                        Spacer(modifier = Modifier.width(4.dp))
                        Text(
                            text = if (isCardBoxed) "Boxed" else "Clean",
                            fontSize = 11.sp,
                            fontWeight = FontWeight.SemiBold,
                            color = colors.tealDark
                        )
                    }
                }
            }
        }

        // 2. Questions (from question_card / QuestionBlock)
        items(paper.questions, key = { "q_${it.num}" }) { q ->
            QuestionCard(
                question = q,
                isCardBoxed = isCardBoxed
            )
        }

        // Section II: Answer Key
        item {
            Spacer(modifier = Modifier.height(14.dp))
            PartHeader(
                partNumber = "SECTION II",
                title = "Official Answer Key",
                countText = "${paper.quickAnswersCount} Keys",
                icon = Icons.Default.CheckCircle
            )
        }

        // 3. Answer Key Table (from answer_key_table)
        item {
            AnswerKeyTable(questions = paper.questions)
        }

        // Section III: Detailed Explanations
        val hasExplanations = paper.questions.any { !it.explanation.isNullOrBlank() || it.correctAnswer != null }
        if (hasExplanations) {
            item {
                Spacer(modifier = Modifier.height(14.dp))
                PartHeader(
                    partNumber = "SECTION III",
                    title = "Detailed Explanations & Solutions",
                    countText = "${paper.explanationsCount} Solutions",
                    icon = Icons.Default.Lightbulb
                )
            }

            // 4. Detailed Explanation Cards (from explanation_card)
            items(
                paper.questions.filter { !it.explanation.isNullOrBlank() || it.correctAnswer != null },
                key = { "exp_${it.num}" }
            ) { q ->
                ExplanationCard(question = q)
            }
        }

        // Bottom padding
        item { Spacer(modifier = Modifier.height(32.dp)) }
    }
}

@Composable
private fun PartHeader(
    partNumber: String,
    title: String,
    countText: String,
    icon: ImageVector,
    modifier: Modifier = Modifier
) {
    val colors = ExamTheme.colors
    Column(
        modifier = modifier
            .fillMaxWidth()
            .padding(vertical = 4.dp)
    ) {
        Row(
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            Surface(
                shape = RoundedCornerShape(4.dp),
                color = colors.navyBanner
            ) {
                Text(
                    text = partNumber,
                    fontSize = 10.sp,
                    fontWeight = FontWeight.Bold,
                    color = colors.navyBannerText,
                    modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp)
                )
            }

            Text(
                text = title,
                fontSize = 15.sp,
                fontWeight = FontWeight.Bold,
                color = colors.inkBold
            )

            Surface(
                shape = RoundedCornerShape(10.dp),
                color = colors.tealLight
            ) {
                Text(
                    text = countText,
                    fontSize = 10.5.sp,
                    fontWeight = FontWeight.SemiBold,
                    color = colors.tealDark,
                    modifier = Modifier.padding(horizontal = 7.dp, vertical = 2.dp)
                )
            }
        }

        Spacer(modifier = Modifier.height(4.dp))

        HorizontalDivider(
            thickness = 1.dp,
            color = colors.teal.copy(alpha = 0.35f)
        )
    }
}
